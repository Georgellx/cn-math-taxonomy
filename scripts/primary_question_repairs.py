def repair_questions(choice, cubes, plane):
    out=[]
    all_specs={tid:[(item,None) for item in items] for tid,items in SPECS.items()}
    all_specs.update(visual_specs(cubes,plane))
    for tid,items in all_specs.items():
        for n,(item,fig) in enumerate(items,1):
            topic_id=f'cnm_p{tid:03}'
            if 'options' in item:
                options=item['options'][:]
                correct=item.get('answer_index',0)
                if 'choice_figures' not in item:
                    shift=(n-1)%len(options)
                    options=options[-shift:]+options[:-shift] if shift else options
                    correct=shift
                explanation=item['explanation'] or ('按题目条件判断，正确的是：'+options[correct]+'。')
                q=choice(topic_id,n,item['prompt'],options,correct,explanation,fig,item.get('choice_figures'))
            else:
                q={'id':f'{topic_id}_q{n}', 'topicId':topic_id,
                   'difficulty':'basic' if n<=2 else 'standard', 'type':'numeric',
                   'prompt':item['prompt'], 'answer':item['answer'], 'verify':item['verify'],
                   'explanation':item['explanation'] or '根据题目给出的条件及本知识点的方法作答。',
                   'fixed_from_source':'广州适配第二轮：按本项目掌握标准修正题目错配；不是教材原题或教师审定。'}
                if fig:q['figure']=fig
            out.append(q)
    # 二上厘米的认识不提前要求三上毫米换算。
    q=numeric('把直尺的0刻度对准纸条一端，另一端对准4厘米刻度。纸条长几厘米？',4)
    q['explanation']='从0厘米量到4厘米，纸条长4厘米。'
    out.append({'id':'cnm_p040_q2','topicId':'cnm_p040','difficulty':'basic','type':'numeric',**q,
                'fixed_from_source':'广州适配第二轮：厘米的认识不提前检查毫米换算。'})
    return out
